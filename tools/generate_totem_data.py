"""Builds Data/Totems.lua from the Forever client's tables on wago.tools.

Every totem a shaman learns from a trainer (the three shaman skill lines): its element (from
SpellTotems: the totem tool it needs), every rank with the level it's learned at, the totem's duration
(SpellMisc + SpellDuration) and, for totems that put a buff on the party, a spell ID carrying the
buff's name (the totem name without " Totem", for example "Strength of Earth"), so the addon can
look for that buff on party members in any client language. Also every weapon imbue ("... Weapon").

Usage:
  python tools/generate_totem_data.py [--build 1.60.1.70532] [--data DIR]
"""
import argparse
import csv
import io
import json
import os
import sys
import urllib.request
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "NullgatesTotems-Forever", "Data", "Totems.lua")
TABLES = ("SpellName", "SpellLevels", "SpellMisc", "SpellDuration", "SpellTotems", "SkillLineAbility")
SHAMAN_LINES = {"375", "373", "374"}
ELEMENTS = {"2": "earth", "4": "fire", "5": "water", "3": "air"}
NOT_PARTY_BUFFS = {"Earthbind"}   # its aura is a slow on enemies
IMBUE_SUFFIX = " Weapon"           # Rockbiter Weapon, Flametongue Weapon, ...


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "NullgatesTotems-generator"})
    with urllib.request.urlopen(req, timeout=300) as resp:
        return resp.read().decode("utf-8")


def latest_build():
    return json.loads(fetch("https://wago.tools/api/builds/latest"))["wow_classic_beta"]["version"]


def load(name, build, data_dir):
    if data_dir:
        with open(os.path.join(data_dir, name + ".csv"), encoding="utf-8") as f:
            text = f.read()
    else:
        text = fetch("https://wago.tools/db2/%s/csv?build=%s" % (name, build))
    return list(csv.DictReader(io.StringIO(text)))


def to_int(value):
    try:
        return int(float(value))
    except (TypeError, ValueError):
        return 0


def build(t):
    names = {r["ID"]: r["Name_lang"] for r in t["SpellName"]}
    levels = {r["SpellID"]: to_int(r.get("SpellLevel")) or to_int(r.get("BaseLevel")) for r in t["SpellLevels"]}
    misc = {r["SpellID"]: r for r in t["SpellMisc"]}
    durations = {r["ID"]: to_int(r["Duration"]) for r in t["SpellDuration"]}
    totem_tool = {r["SpellID"]: r["RequiredTotemCategoryID_0"] for r in t["SpellTotems"]}
    ids_by_name = defaultdict(list)
    for spell, name in names.items():
        ids_by_name[name].append(to_int(spell))

    totems = {}
    for r in t["SkillLineAbility"]:
        spell = r["Spell"]
        name = names.get(spell, "")
        if r["SkillLine"] not in SHAMAN_LINES or not name.endswith(" Totem") or not levels.get(spell):
            continue
        element = ELEMENTS.get(totem_tool.get(spell))
        if not element:
            continue
        m = misc.get(spell)
        duration = durations.get(m["DurationIndex"], 0) // 1000 if m else 0
        entry = totems.setdefault(name, {"name": name, "element": element, "ranks": [], "duration": 0})
        entry["ranks"].append({"spell": to_int(spell), "level": levels[spell]})
        entry["duration"] = max(entry["duration"], duration)
    for entry in totems.values():
        entry["ranks"].sort(key=lambda x: x["level"])
        buff = entry["name"][:-len(" Totem")]
        entry["buffSpell"] = min(ids_by_name[buff]) if ids_by_name.get(buff) and buff not in NOT_PARTY_BUFFS else 0
    if len({e["element"] for e in totems.values()}) != 4:
        sys.exit("expected totems of all four elements")

    imbues = {}
    for r in t["SkillLineAbility"]:
        spell = r["Spell"]
        name = names.get(spell, "")
        if r["SkillLine"] in SHAMAN_LINES and name.endswith(IMBUE_SUFFIX) and levels.get(spell):
            imbues.setdefault(name, []).append({"spell": to_int(spell), "level": levels[spell]})
    for ranks in imbues.values():
        ranks.sort(key=lambda x: x["level"])
    if not imbues:
        sys.exit("no weapon imbues found")
    return totems, imbues


ORDER = ("earth", "fire", "water", "air")


def write(build_id, totems, imbues):
    lines = [
        "-- Generated by tools/generate_totem_data.py from the Forever client data. Do not edit by hand.",
        "local _, ns = ...",
        "",
        'ns.TOTEM_DATA_BUILD = "%s"' % build_id,
        "",
        "-- Per element, every totem: key, English name, duration in seconds, a spell ID carrying the name of",
        "-- the buff it puts on the party (0 = no party buff) and its ranks (spell ID, level learned).",
        "ns.TOTEMS = {",
    ]
    for element in ORDER:
        lines.append("    %s = {" % element)
        for e in sorted((e for e in totems.values() if e["element"] == element), key=lambda e: (e["ranks"][0]["level"], e["name"])):
            key = e["name"][:-len(" Totem")].lower().replace(" ", "").replace("'", "")
            ranks = ", ".join("{ %d, %d }" % (r["spell"], r["level"]) for r in e["ranks"])
            lines.append('        { key = "%s", name = "%s", duration = %d, buffSpell = %d, ranks = { %s } },' % (
                key, e["name"], e["duration"], e["buffSpell"], ranks))
        lines.append("    },")
    lines.append("}")
    lines += ["", "-- Weapon imbues, in the order they're learned: key, English name, ranks (spell ID, level learned).",
              "ns.IMBUES = {"]
    for name, ranks in sorted(imbues.items(), key=lambda kv: kv[1][0]["level"]):
        key = name[:-len(IMBUE_SUFFIX)].lower()
        lines.append('    { key = "%s", name = "%s", ranks = { %s } },' % (key, name, ", ".join("{ %d, %d }" % (x["spell"], x["level"]) for x in ranks)))
    lines.append("}")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--build")
    parser.add_argument("--data")
    args = parser.parse_args()
    build_id = args.build or latest_build()
    totems, imbues = build({name: load(name, build_id, args.data) for name in TABLES})
    write(build_id, totems, imbues)
    for element in ORDER:
        print("%-6s %s" % (element, ", ".join("%s (%ds%s)" % (e["name"], e["duration"], ", buff" if e["buffSpell"] else "")
                                             for e in totems.values() if e["element"] == element)))
    print("imbues", ", ".join(imbues))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
